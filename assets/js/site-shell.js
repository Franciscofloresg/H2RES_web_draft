  // Ensure a <main id="main"> landmark exists so the skip link has a target
  // and assistive tech can jump to the content. Most subpages already ship a
  // <main>; there we just tag it. The home has none, so we wrap its content.
  function wrapMainLandmark() {
    const existing = document.querySelector("main");
    if (existing) {
      if (!existing.id) existing.id = "main";
      if (!existing.hasAttribute("tabindex")) existing.setAttribute("tabindex", "-1");
      return;
    }
    const header = document.querySelector(".site-header");
    if (!header) return;
    // Content starts after the header and its injected mobile-nav sibling.
    let start = header;
    const mobileNav = document.getElementById("mobileNav");
    if (mobileNav) start = mobileNav;
    const main = document.createElement("main");
    main.id = "main";
    main.setAttribute("tabindex", "-1");
    const between = [];
    let node = start.nextSibling;
    while (node) {
      if (node.nodeType === 1 && node.classList && node.classList.contains("site-footer")) break;
      between.push(node);
      node = node.nextSibling;
    }
    start.after(main);
    between.forEach((n) => main.appendChild(n));
  }

  function initTheme() {
    // Theme handling for the whole site: default to the OS preference,
    // allow a manual toggle in the header, and remember the choice.
    const html = document.documentElement;
    const prefersDark = window.matchMedia("(prefers-color-scheme: dark)");

    function storedTheme() {
      try { return localStorage.getItem("theme"); } catch (e) { return null; }
    }
    function applyTheme(theme, persist) {
      html.setAttribute("data-theme", theme);
      if (persist) { try { localStorage.setItem("theme", theme); } catch (e) {} }
    }

    const current = html.getAttribute("data-theme");
    if (current !== "dark" && current !== "light") {
      applyTheme(storedTheme() || (prefersDark.matches ? "dark" : "light"), false);
    }

    const onSystemChange = (event) => {
      if (!storedTheme()) applyTheme(event.matches ? "dark" : "light", false);
    };
    if (typeof prefersDark.addEventListener === "function") {
      prefersDark.addEventListener("change", onSystemChange);
    } else if (typeof prefersDark.addListener === "function") {
      prefersDark.addListener(onSystemChange);
    }

    const themeToggle = document.getElementById("themeToggle");
    if (themeToggle) {
      themeToggle.addEventListener("click", () => {
        const next = html.getAttribute("data-theme") === "dark" ? "light" : "dark";
        applyTheme(next, true);
      });
    }
  }

  // Site-wide "back to top" control: a floating button that appears once the
  // page is scrolled past the first viewport and returns to the top on click.
  function initBackToTop() {
    if (document.querySelector(".back-to-top")) return;
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "back-to-top";
    btn.setAttribute("aria-label", "Back to top");
    btn.setAttribute("hidden", "");
    btn.innerHTML = '<svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><line x1="12" y1="19" x2="12" y2="5"/><polyline points="5 12 12 5 19 12"/></svg>';
    document.body.appendChild(btn);

    const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    const THRESHOLD = 600;
    let visible = false;
    let ticking = false;

    function update() {
      const shouldShow = window.scrollY > THRESHOLD;
      if (shouldShow !== visible) {
        visible = shouldShow;
        if (shouldShow) {
          btn.removeAttribute("hidden");
          // Force reflow so the fade-in transition runs after unhide.
          void btn.offsetWidth;
          btn.classList.add("is-visible");
        } else {
          btn.classList.remove("is-visible");
        }
      }
      ticking = false;
    }

    btn.addEventListener("transitionend", (event) => {
      if (event.propertyName === "opacity" && !visible) {
        btn.setAttribute("hidden", "");
      }
    });

    window.addEventListener("scroll", () => {
      if (!ticking) {
        window.requestAnimationFrame(update);
        ticking = true;
      }
    }, { passive: true });

    btn.addEventListener("click", () => {
      window.scrollTo({ top: 0, behavior: reduceMotion ? "auto" : "smooth" });
      const main = document.getElementById("main");
      if (main && typeof main.focus === "function") {
        main.focus({ preventScroll: true });
      }
    });

    update();
  }

