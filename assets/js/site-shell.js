  function escapeHtml(text) {
    return String(text || "")
      .replaceAll("&", "&amp;")
      .replaceAll("<", "&lt;")
      .replaceAll(">", "&gt;")
      .replaceAll('"', "&quot;")
      .replaceAll("'", "&#39;");
  }

  function normalizeRoot(root) {
    if (!root) {
      return "../";
    }
    return root.endsWith("/") ? root : `${root}/`;
  }

